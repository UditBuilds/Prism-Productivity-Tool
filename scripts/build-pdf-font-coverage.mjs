/**
 * Generate `lib/notes/pdf-font-coverage.json` from the vendored PDF fonts.
 *
 * WHY THIS EXISTS. When a codepoint is present in NO font of a react-pdf font
 * stack, the renderer does not fall back to a blank or a .notdef box — it
 * throws `Offset is outside the bounds of the DataView` and the whole export
 * fails. Five characters in the live notes table hit that today (U+2011
 * non-breaking hyphen ×136, U+202F narrow no-break space ×20, and ≈ ≤ ≥), and
 * nothing stops a future note from containing an emoji or a CJK character.
 *
 * So the renderer needs to know, before it starts, which codepoints it can
 * safely draw. Deriving that from the font files themselves — rather than
 * hand-maintaining a list — means it cannot go stale silently: change the
 * vendored fonts, re-run this, and the coverage follows.
 *
 * Run after adding or replacing anything in public/fonts/pdf:
 *   node scripts/build-pdf-font-coverage.mjs
 */
import * as fontkit from "fontkit";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const FONT_DIR = path.join("public", "fonts", "pdf");

// Every face registered by lib/notes/generate-note-pdf.tsx. Both font stacks
// there list all three families, so one union is the right coverage set for
// both — see the comment on SANS_STACK.
const FILES = [
  "InstrumentSans-Regular.ttf",
  "InstrumentSans-Italic.ttf",
  "InstrumentSans-SemiBold.ttf",
  "InstrumentSans-Bold.ttf",
  "JetBrainsMono-Regular.ttf",
  "NotoSansDevanagari-Regular.ttf",
];

const covered = new Set();
for (const file of FILES) {
  const font = fontkit.create(readFileSync(path.join(FONT_DIR, file)));
  for (const cp of font.characterSet) covered.add(cp);
}

// Collapse to sorted [start, end] ranges — a few hundred pairs instead of
// thousands of integers, and a binary search away from an O(log n) lookup.
const sorted = [...covered].sort((a, b) => a - b);
const ranges = [];
for (const cp of sorted) {
  const last = ranges[ranges.length - 1];
  if (last && cp === last[1] + 1) last[1] = cp;
  else ranges.push([cp, cp]);
}

const out = {
  _comment:
    "GENERATED by scripts/build-pdf-font-coverage.mjs — do not edit by hand. " +
    "Sorted, inclusive [start, end] codepoint ranges covered by the union of " +
    "the fonts in public/fonts/pdf.",
  fonts: FILES,
  codepoints: covered.size,
  ranges,
};

const dest = path.join("lib", "notes", "pdf-font-coverage.json");
writeFileSync(dest, JSON.stringify(out, null, 0) + "\n");

console.log(
  `${covered.size} codepoints across ${FILES.length} faces → ${ranges.length} ranges`
);
console.log(`wrote ${dest} (${JSON.stringify(out).length} bytes)`);
